"""Holdout evaluation of the champion model + Markdown model card.

Evaluates on the stratified test split that training never saw:
accuracy, precision, recall, F1, ROC-AUC, average precision, confusion
matrix, and a per-threshold precision/recall table. Writes
artifacts/reports/model_card.md with the real numbers.

Usage:
    python evaluate.py            # evaluates the registry champion
    python evaluate.py <exp_id>    # evaluates a specific experiment
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import (accuracy_score, average_precision_score,
                             confusion_matrix, f1_score, precision_recall_curve,
                             precision_score, recall_score, roc_auc_score)

import data
import registry
from config import CHAMPION_METRIC, REPORTS_DIR


def evaluate_model(pipeline, X_test: pd.DataFrame, y_test: pd.Series) -> dict:
    proba = pipeline.predict_proba(X_test)[:, 1]
    pred = pipeline.predict(X_test)
    tn, fp, fn, tp = confusion_matrix(y_test, pred).ravel()
    precision, recall, thresholds = precision_recall_curve(y_test, proba)
    return {
        "n_test": int(len(y_test)),
        "accuracy": float(accuracy_score(y_test, pred)),
        "precision": float(precision_score(y_test, pred)),
        "recall": float(recall_score(y_test, pred)),
        "f1": float(f1_score(y_test, pred)),
        "roc_auc": float(roc_auc_score(y_test, proba)),
        "avg_precision": float(average_precision_score(y_test, proba)),
        "confusion_matrix": {"tn": int(tn), "fp": int(fp),
                             "fn": int(fn), "tp": int(tp)},
        # Threshold sweep for the model card (every 10th point to stay compact)
        "threshold_sweep": [
            {"threshold": float(t), "precision": float(p), "recall": float(r)}
            for t, p, r in zip(thresholds[::10], precision[::10], recall[::10])
        ],
    }


def render_model_card(exp: dict, metrics: dict, profile: dict) -> str:
    cm = metrics["confusion_matrix"]
    sweep = "\n".join(
        f"| {s['threshold']:.2f} | {s['precision']:.3f} | {s['recall']:.3f} |"
        for s in metrics["threshold_sweep"]
    )
    return f"""# Model card: {exp['experiment_id']}

Generated by drift-guard `evaluate.py`. All numbers are measured on the
stratified holdout split the model never saw during training or tuning.

## Model
- Algorithm: {exp['model']} (scikit-learn pipeline: median imputation -> standard scaling -> classifier)
- Champion metric (5-fold CV): {CHAMPION_METRIC} = {exp['cv_scores'][CHAMPION_METRIC]:.4f}
- Best hyperparameters: `{exp['params']}`
- Trained on {exp['train_rows']} rows x {exp['n_features']} features, {exp['timestamp']}

## Dataset
- {profile['dataset']}: {profile['n_rows']} rows, {profile['n_features']} features
- Positive rate: {profile['positive_rate']:.3f} (class counts {profile['class_counts']})

## Holdout metrics (n={metrics['n_test']})
| Metric | Value |
|---|---|
| Accuracy | {metrics['accuracy']:.4f} |
| Precision | {metrics['precision']:.4f} |
| Recall | {metrics['recall']:.4f} |
| F1 | {metrics['f1']:.4f} |
| ROC-AUC | {metrics['roc_auc']:.4f} |
| Average precision | {metrics['avg_precision']:.4f} |

## Confusion matrix (threshold 0.5)
| | Pred negative | Pred positive |
|---|---|---|
| Actual negative | {cm['tn']} | {cm['fp']} |
| Actual positive | {cm['fn']} | {cm['tp']} |

## Precision/recall vs threshold
| Threshold | Precision | Recall |
|---|---|---|
{sweep}

## Intended use and limits
- Demo/benchmark pipeline: shows training, experiment tracking, holdout
  evaluation, drift monitoring, and serving in one reproducible repo.
- Not a medical device. The demo dataset is a classic ML benchmark, not a
  clinical validation set.
"""


def main(exp_id: str | None = None) -> Path:
    exp = (registry.champion_experiment(CHAMPION_METRIC) if exp_id is None
           else next(r for r in registry.list_experiments()
                     if r["experiment_id"] == exp_id))
    pipeline = registry.load_model(exp["experiment_id"])

    df = data.load_dataset()
    _, X_test, _, y_test = data.split_data(df)
    metrics = evaluate_model(pipeline, X_test, y_test)

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    card_path = REPORTS_DIR / "model_card.md"
    card_path.write_text(render_model_card(exp, metrics, data.describe(df)))
    print(f"[evaluate] {exp['experiment_id']}: "
          f"acc={metrics['accuracy']:.4f} f1={metrics['f1']:.4f} "
          f"roc_auc={metrics['roc_auc']:.4f}")
    print(f"[evaluate] model card -> {card_path}")
    return card_path


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
